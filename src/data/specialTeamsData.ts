export type SpecialTeamsUnitId = 'kickoff' | 'kick_return' | 'punt_coverage' | 'punt_return' | 'fg_pat' | 'fg_block';

export interface STPlayer {
  id: string;
  label: string;
  number: string;
  name: string;
  role: string;
  x: number; // 0 to 1000
  y: number; // 0 to 620
  targetX?: number; // End of initial path
  targetY?: number;
  waypoints?: { x: number; y: number }[];
  responsibility: string;
  coachingCue: string;
  isKickerOrKey?: boolean;
  schemeVariants?: Record<
    string,
    {
      x?: number;
      y?: number;
      targetX?: number;
      targetY?: number;
      waypoints?: { x: number; y: number }[];
      responsibility?: string;
      coachingCue?: string;
      role?: string;
      label?: string;
    }
  >;
}

export function getActiveSTPlayer(player: STPlayer, schemeId: string): STPlayer {
  if (player.schemeVariants && player.schemeVariants[schemeId]) {
    return {
      ...player,
      ...player.schemeVariants[schemeId],
    };
  }
  return player;
}

